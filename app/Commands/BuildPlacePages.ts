function codeSheetFor(slug: string): string {
  return `<script server>
// Generated by \`buddy build:places\`. Do not edit this file; the markup is in
// resources/partials/code-sheet.stx and the logic in
// resources/functions/code-sheet.ts.
// The partial below calls \`t\`, not this file, which the linter cannot see
// from here.
// eslint-disable-next-line unused-imports/no-unused-imports
import { currentLocale, t } from '../../../app/Actions/Locale/translate'

/*
 * The page's own facts, and nothing else.
 *
 * The codes themselves used to be read here and rendered into the page, which
 * put every restaurant's table codes behind a guessable URL and no account.
 * The sheet now asks \`/api/manage/{slug}/codes\` for them, which checks the
 * permission and the team.
 */
const pageTitle = t('meta.codes_title')
const pageDescription = t('meta.codes_description')
const canonicalPath = '/codes/${slug}'
</script>

<!DOCTYPE html>
<html lang="{{ currentLocale() }}">
  <head>
    @include('head')
    <style>
      /* The sheet is for printing. Everything that is not a code gets out of
         the way, and each card is kept whole across a page break. */
      @media print {
        .no-print { display: none !important; }
        body { background: #fff; }
        .code-card { break-inside: avoid; box-shadow: none !important; border: 1px solid #ddd; }
      }
    </style>
  </head>

  <body>
    <div class="no-print">
      @include('chrome')
    </div>

    @include('code-sheet')

    <script client>
      import { codeSheet } from '../../functions/code-sheet'

      /*
       * The signals are declared here, in the page's own script, because that
       * is the only place stx looks when it builds a page's setup. Handed back
       * from a factory and destructured, they are invisible to it and every
       * binding on the page silently does nothing.
       *
       * Named \`sheet\` rather than \`codes\`: this page is served at
       * /codes/<slug>, and a bare \`codes\` resolved to that path segment.
       */
      const sheet = state([])
      const loading = state(true)

      /* Who is signed in; see functions/session.ts. */
      const signedIn = state(false)
      const denied = state(false)

      /* This sheet is one business's, named above, so there is nothing to
         switch between - but partials/operator-empty is shared with the
         screens that have. */
      const mine = state([])
      const slug = state('')

      /* What this page resolved; see partials/operator-empty.stx. */
      const allowed = derived(() => sheet().length > 0)

      function operatorLink() {
        return '/codes/${slug}'
      }

      const { load } = codeSheet('${slug}', { sheet, loading, signedIn, denied, slug })

      load()
    </script>
  </body>
</html>
`
}
